import type { CourseSeedTopic, CourseSeedTopicSection } from './courseSeedContent';

const draftStatus = 'Draft/source-filled from content-model/P1/p1-content map.pdf and topic PDFs; needs syllabus-contract review before mastery, readiness, or final exam-route use.';
const draftPromptPrefix = 'Draft/generated practice';

interface P1SubtopicSpec {
  id: string;
  title: string;
  goal: string;
  method: string;
  example: string;
  mistake: string;
  takeaway: string;
  prompt: string;
}

interface P1TopicSpec {
  id: string;
  slug: string;
  syllabusRef: string;
  title: string;
  shortTitle: string;
  description: string;
  headerFormula: string;
  formulas: string[];
  studentGoals: string[];
  keyIdeas: string[];
  workedMethod: string[];
  commonMistakes: string[];
  selfChecks: string[];
  examStyle: string[];
  practiceHook: string;
  examTrainingHook: string;
  subtopics: P1SubtopicSpec[];
}

function section(topicId: string, spec: P1SubtopicSpec): CourseSeedTopicSection {
  return {
    id: `${topicId}-${spec.id}`,
    title: spec.title,
    purpose: spec.goal,
    bullets: [
      `Learning goal: ${spec.goal}`,
      `Key method: ${spec.method}`,
      `Draft worked example: ${spec.example}`,
      `Common mistake: ${spec.mistake}`,
      `Quick takeaway: ${spec.takeaway}`,
    ],
    practicePrompts: [`${draftPromptPrefix}: ${spec.prompt}`],
  };
}

function topic(spec: P1TopicSpec): CourseSeedTopic {
  return {
    courseId: 'p1',
    id: spec.id,
    slug: spec.slug,
    syllabusRef: spec.syllabusRef,
    title: spec.title,
    shortTitle: spec.shortTitle,
    description: spec.description,
    headerFormula: spec.headerFormula,
    formulas: spec.formulas,
    studentGoals: spec.studentGoals,
    keyIdeas: spec.keyIdeas,
    workedMethod: spec.workedMethod,
    commonMistakes: spec.commonMistakes,
    selfChecks: spec.selfChecks,
    examStyle: spec.examStyle,
    practiceHook: spec.practiceHook,
    examTrainingHook: spec.examTrainingHook,
    reviewStatus: draftStatus,
    genericPracticePrompts: spec.subtopics.map((subtopic) => `${draftPromptPrefix}: ${subtopic.prompt}`),
    fieldGuideSections: spec.subtopics.map((subtopic) => section(spec.id, subtopic)),
  };
}

