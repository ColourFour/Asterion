export function normalizeUnitImprovementTopicToken(token: string): string {
  const normalized = token
    .trim()
    .toLowerCase()
    .replace(/^p3[-_\s]+/, '')
    .replace(/[_\s]+/g, '-');
  return UNIT_IMPROVEMENT_TOPIC_ALIASES[normalized] ?? normalized;
}

