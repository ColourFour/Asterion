import type { SkillCheckItem } from './skillCheckItems';

type P1Spec = {
  itemId: string;
  topicId: string;
  subtopicId: string;
  skillId: string;
  prompt: string;
  expectedAnswer: string | string[];
  suffix?: string;
  commonMistake: string;
  nudge: string;
  firstStep: string;
  workedRoute: string[];
  complexity?: SkillCheckItem['complexity'];
};

const review = (): SkillCheckItem['review'] => ({
  status: 'draft_review_needed',
  sourceSkillReviewed: false,
  markEventReviewed: false,
  affectsMastery: false,
  supportOnly: true,
  evidenceEnabled: false,
});

const sourceRefs = (): SkillCheckItem['sourceRefs'] => ({
  courseContentSource: 'content-model/P1/p1-content map.pdf',
});

function item(spec: P1Spec): SkillCheckItem {
  return {
    itemId: spec.itemId,
    courseId: 'p1',
    paperFamily: 'p1',
    regionId: 'p1-draft-skill-check',
    fieldGuideTopicId: spec.topicId,
    fieldGuideSubtopicId: spec.subtopicId,
    skillId: spec.skillId,
    prompt: spec.prompt,
    inputType: 'numeric',
    validationMode: 'deterministic',
    expectedAnswer: spec.expectedAnswer,
    displaySuffix: spec.suffix,
    complexity: spec.complexity ?? 'foundation',
    commonMistake: spec.commonMistake,
    hints: {
      nudge: spec.nudge,
      methodCue: 'Use the matching draft Field Guide method before simplifying.',
      firstStep: spec.firstStep,
    },
    workedRoute: spec.workedRoute,
    sourceTypes: ['authored'],
    sourceRefs: sourceRefs(),
    review: review(),
  };
}

