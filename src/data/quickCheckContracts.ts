import type { QuickCheckContract } from '../types';

type QuickCheckContractDraft = Omit<QuickCheckContract, 'answerType'>;
type SingleChoiceContractDraft = Omit<QuickCheckContract, 'answerType' | 'expectedChoices'> & {
  expectedChoice: string;
};

function singleValueContract(contract: QuickCheckContractDraft): QuickCheckContract {
  return { answerType: 'single_value', ...contract };
}

function singleChoiceContract({ expectedChoice, ...contract }: SingleChoiceContractDraft): QuickCheckContract {
  return {
    answerType: 'choice',
    expectedChoices: [expectedChoice],
    ...contract,
  };
}

