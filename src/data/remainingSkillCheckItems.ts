import type { QuickCheckOption, QuickCheckTwoValueField } from '../types';
import type { P3RegionId, P3SkillId } from '../lib/p3SkillContract';
import type { SkillCheckComplexity, SkillCheckInputType, SkillCheckItem } from './skillCheckItems';
import type { SkillCheckAnswerType } from '../skill-checks/answerChecker';

const SKILL_MAP_SOURCE = 'tools/content_lab/skill_maps/caie_9709_p3_skill_map.json' as const;

interface ChoiceSpec {
  complexity: SkillCheckComplexity;
  prompt: string;
  correct: string;
  distractors: [string, string, string];
  inputType?: Extract<SkillCheckInputType, 'multiple_choice' | 'checkbox' | 'numeric' | 'ordered_cards' | 'two_value'>;
  expectedAnswer?: string | string[];
  expectedOptionIds?: string[];
  options?: QuickCheckOption[];
  expectedOrder?: string[];
  cards?: QuickCheckOption[];
  fields?: QuickCheckTwoValueField[];
  displayPrefix?: string;
  displaySuffix?: string;
  tolerance?: number;
  answerType?: SkillCheckAnswerType;
  acceptedAnswers?: string[];
  orderInsensitive?: boolean;
  repairStep?: string;
  mistakeTags?: string[];
  checkable?: boolean;
  unsupportedAnswerReason?: string;
  nudge: string;
  methodCue?: string;
  firstStep?: string;
  workedRoute: [string, string, string];
}

interface TopicSpec {
  regionId: P3RegionId;
  topicId: string;
  skillId: P3SkillId;
  slug: string;
  items: [ChoiceSpec, ChoiceSpec, ChoiceSpec];
}

function option(label: string, index: number): QuickCheckOption {
  return {
    id: index === 0 ? 'correct' : `distractor-${index}`,
    label,
  };
}

function choiceItem(topic: TopicSpec, spec: ChoiceSpec): SkillCheckItem {
  const inputType = spec.inputType ?? 'multiple_choice';
  const choiceOptions = spec.options ?? [spec.correct, ...spec.distractors].map(option);
  return {
    itemId: `sc-${topic.slug}-${spec.complexity}-001`,
    paperFamily: 'p3',
    regionId: topic.regionId,
    fieldGuideTopicId: topic.topicId,
    fieldGuideSubtopicId: topic.topicId,
    skillId: topic.skillId,
    prompt: spec.prompt,
    inputType,
    validationMode: 'deterministic',
    expectedAnswer: inputType === 'numeric' ? spec.expectedAnswer ?? spec.correct : undefined,
    expectedOptionIds: inputType === 'multiple_choice' || inputType === 'checkbox'
      ? spec.expectedOptionIds ?? ['correct']
      : undefined,
    expectedOrder: inputType === 'ordered_cards' ? spec.expectedOrder : undefined,
    options: inputType === 'multiple_choice' || inputType === 'checkbox' ? choiceOptions : undefined,
    cards: inputType === 'ordered_cards' ? spec.cards : undefined,
    fields: inputType === 'two_value' ? spec.fields : undefined,
    displayPrefix: spec.displayPrefix,
    displaySuffix: spec.displaySuffix,
    tolerance: spec.tolerance,
    answerType: spec.answerType,
    acceptedAnswers: spec.acceptedAnswers,
    orderInsensitive: spec.orderInsensitive,
    repairStep: spec.repairStep,
    mistakeTags: spec.mistakeTags,
    checkable: spec.checkable,
    unsupportedAnswerReason: spec.unsupportedAnswerReason,
    complexity: spec.complexity,
    hints: {
      nudge: spec.nudge,
      methodCue: spec.methodCue,
      firstStep: spec.firstStep,
    },
    workedRoute: spec.workedRoute,
    sourceTypes: ['authored'],
    sourceRefs: { skillMapSource: SKILL_MAP_SOURCE },
    review: {
      status: 'teacher_reviewed',
      sourceSkillReviewed: true,
      markEventReviewed: false,
      affectsProgression: false,
    },
  };
}

function topicItems(topic: TopicSpec): SkillCheckItem[] {
  return topic.items.map((item) => choiceItem(topic, item));
}

